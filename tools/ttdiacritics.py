def decode_table_for_diacritic(db, dc, G0):
	decomp = chr(160) + chr(dc)
	comp = chr(DIACRITICS_SPACING[db][-1]) if db in DIACRITICS_SPACING else decomp
	print('0x%02X\tU+%s\t# %s' % (
		db,
		'+'.join('%04X' % ord(c) for c in comp),
		', '.join(unicodedata.name(c) for c in comp)
	))
	for bb in sorted(G0):
		bc = G0[bb]
		decomp = chr(bc) + chr(dc)
		comp = unicodedata.normalize('NFC', decomp)
		print('0x%02X%02X\tU+%s\t# %s' % (
			db, bb,
			'+'.join('%04X' % ord(c) for c in comp),
			', '.join(unicodedata.name(c) for c in comp)
		))

def encode_table_for_diacritic(db, dc, G0):
	composed = []
	decomp = chr(32) + chr(dc)
	print('U+%s\t0x%02X\t# %s' % (
		'+'.join('%04X' % ord(c) for c in decomp),
		db,
		', '.join(unicodedata.name(c) for c in decomp)
	))
	decomp = chr(160) + chr(dc)
	print('U+%s\t0x%02X\t# %s' % (
		'+'.join('%04X' % ord(c) for c in decomp),
		db,
		', '.join(unicodedata.name(c) for c in decomp)
	))
	if db in DIACRITICS_SPACING:
		for sdc in DIACRITICS_SPACING[db]:
			comp = chr(sdc)
			composed.append('U+%s\t0x%02X\t# %s' % (
				'+'.join('%04X' % ord(c) for c in comp),
				db,
				', '.join(unicodedata.name(c) for c in comp)
			))
	for bb in sorted(G0):
		bc = G0[bb]
		decomp = chr(bc) + chr(dc)
		print('U+%s\t0x%02X%02X\t# %s' % (
			'+'.join('%04X' % ord(c) for c in decomp),
			db, bb,
			', '.join(unicodedata.name(c) for c in decomp)
		))
		comp = unicodedata.normalize('NFC', decomp)
		if comp != decomp:
			composed.append('U+%s\t0x%02X%02X\t# %s' % (
				'+'.join('%04X' % ord(c) for c in comp),
				db, bb,
				', '.join(unicodedata.name(c) for c in comp)
			))
	for line in composed:
		print(line)

def decode_table_for_diacritics(G0):
	for db in sorted(DIACRITICS):
		dc = DIACRITICS[db]
		print('# %s' % unicodedata.name(chr(dc))[10:])
		decode_table_for_diacritic(db, dc, G0)
		print()

def encode_table_for_diacritics(G0):
	for db in sorted(DIACRITICS):
		dc = DIACRITICS[db]
		print('# %s' % unicodedata.name(chr(dc))[10:])
		encode_table_for_diacritic(db, dc, G0)
		print()

def main():
	args = sys.argv[1:]
	for arg in args:
		if arg in ['sr-cyrl', 'hr-cyrl']:
			decode_table_for_diacritics(CYRILLIC_SR_HR)
			encode_table_for_diacritics(CYRILLIC_SR_HR)
		elif arg in ['ru', 'bg']:
			decode_table_for_diacritics(CYRILLIC_RU_BG)
			encode_table_for_diacritics(CYRILLIC_RU_BG)
		elif arg == 'uk':
			decode_table_for_diacritics(CYRILLIC_UK)
			encode_table_for_diacritics(CYRILLIC_UK)
		elif arg == 'el':
			decode_table_for_diacritics(GREEK)
			encode_table_for_diacritics(GREEK)
		else:
			decode_table_for_diacritics(LATIN)
			encode_table_for_diacritics(LATIN)

if __name__ == '__main__':
	main()
