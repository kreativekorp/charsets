def permute_MacRoman(b2c, c2b):
	b2c = {tuple(PERMUTATION[b] for b in bs): b2c[bs] for bs in b2c}
	c2b = {cs: tuple(PERMUTATION[b] for b in c2b[cs]) for cs in c2b}
	return b2c, c2b

def patch_Euro(b2c, c2b):
	b2c = b2c.copy()
	b2c[(0xDB,)] = (0x20AC,)
	c2b = c2b.copy()
	c2b[(0x20AC,)] = (0xDB,)
	return b2c, c2b

def read_maps(lines):
	bytes_to_chars = {}
	chars_to_bytes = {}
	for line in lines:
		line = line.rstrip('\r\n')
		mapping = line.partition('#')[0].strip()
		m = re.match(tablint.BYTES_TO_CHARS, mapping)
		if m:
			bs = tuple(int(m[1][i:i+2],16) for i in range(0,len(m[1]),2))
			cps = tuple(int(cp,16) for cp in m[3][1:].split('+'))
			bytes_to_chars[bs] = cps
			continue
		m = re.match(tablint.CHARS_TO_BYTES, mapping)
		if m:
			cps = tuple(int(cp,16) for cp in m[1][1:].split('+'))
			bs = tuple(int(m[4][i:i+2],16) for i in range(0,len(m[4]),2))
			chars_to_bytes[cps] = bs
			continue
	return bytes_to_chars, chars_to_bytes

def print_maps(b2c, c2b):
	for bs in sorted(b2c):
		print('0x%s\tU+%s\t# %s' % (
			''.join('%02X' % b for b in bs),
			'+'.join('%04X' % c for c in b2c[bs]),
			', '.join(CONTROL_NAMES[c] if c in CONTROL_NAMES else unicodedata.name(chr(c), '') for c in b2c[bs])
		))
	print()
	for cs in sorted(c2b):
		print('U+%s\t0x%s\t# %s' % (
			'+'.join('%04X' % c for c in cs),
			''.join('%02X' % b for b in c2b[cs]),
			', '.join(CONTROL_NAMES[c] if c in CONTROL_NAMES else unicodedata.name(chr(c), '') for c in cs)
		))

def process_lines(lines, prepatch_Euro, postpatch_Euro):
	bytes_to_chars, chars_to_bytes = read_maps(lines)
	if prepatch_Euro:
		bytes_to_chars, chars_to_bytes = patch_Euro(bytes_to_chars, chars_to_bytes)
	bytes_to_chars, chars_to_bytes = permute_MacRoman(bytes_to_chars, chars_to_bytes)
	if postpatch_Euro:
		bytes_to_chars, chars_to_bytes = patch_Euro(bytes_to_chars, chars_to_bytes)
	print_maps(bytes_to_chars, chars_to_bytes)

def main():
	process_options = True
	prepatch_Euro = False
	postpatch_Euro = False
	processed_input = False
	args = sys.argv[1:]
	for arg in args:
		if process_options and arg.startswith('-'):
			if arg == '--':
				process_options = False
			elif arg == '-e':
				prepatch_Euro = False
				postpatch_Euro = True
			elif arg == '-f':
				prepatch_Euro = True
				postpatch_Euro = False
			elif arg == '-n':
				prepatch_Euro = False
				postpatch_Euro = False
			elif arg == '-i':
				process_lines(sys.stdin, prepatch_Euro, postpatch_Euro)
				processed_input = True
			else:
				print('Error: Unknown option: %s' % arg)
				return False
		else:
			with open(arg, 'r') as f:
				process_lines(f, prepatch_Euro, postpatch_Euro)
				processed_input = True
	if not processed_input:
		process_lines(sys.stdin, prepatch_Euro, postpatch_Euro)

if __name__ == '__main__':
	main()
