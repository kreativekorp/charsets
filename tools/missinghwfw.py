def check_missing_hwfw(file):
	chars_to_bytes = {}
	with open(file, 'r') as f:
		for line in f:
			line, _, _ = [p.strip() for p in line.partition('#')]
			m = re.match(tablint.CHARS_TO_BYTES, line)
			if m:
				cps = tuple(int(cp,16) for cp in m[1][1:].split('+'))
				bs = tuple(int(m[4][i:i+2],16) for i in range(0,len(m[4]),2))
				chars_to_bytes[cps] = bs
	for std, hwfw in HALFWIDTH_FULLWIDTH_FORMS:
		if (std,) in chars_to_bytes and (hwfw,) not in chars_to_bytes:
			bs = ''.join('%02X' % b for b in chars_to_bytes[(std,)])
			print('U+%04X\t0x%s\t# %s' % (hwfw, bs, unicodedata.name(chr(hwfw))))

def main():
	args = sys.argv[1:]
	for arg in args:
		print(arg)
		check_missing_hwfw(arg)

if __name__ == '__main__':
	main()
